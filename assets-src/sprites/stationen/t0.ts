/** Legt ein Raster (`.` = Grundbild bleibt) mit eigener Legende über einen Frame. */
function ueberlagert(f: SpriteFrame, w: number, raster: string, legende: Readonly<Record<string, string>>): PixelFrameInput {
  const index = Uint8Array.from(f.index);
  const emissive = Uint8Array.from(f.emissive);
  const material = Uint8Array.from(f.material);
  raster
    .split('\n')
    .map((z) => z.trim())
    .filter((z) => z.length > 0)
    .forEach((z, y) => {
      for (let x = 0; x < z.length; x++) {
        const ref = legende[z.charAt(x)];
        if (ref === undefined) continue;
        const r = resolveColor(ref);
        if ('error' in r) throw new Error(`Überlagerung: ${r.error}`);
        const p = y * w + x;
        index[p] = r.index;
        emissive[p] = r.emissive ? 1 : 0;
        material[p] = 0;
      }
    });
  return { index, emissive, material };
}

