/** Flammen im Schürloch (vier Formen) und Glut im Abzug. */
function ofenFeuer(flammen: readonly string[]): string {
  const leer = '................................';
  const zeilen = Array.from({ length: 32 }, () => leer);
  zeilen[4] = '..............}}}}..............';
  flammen.forEach((z, i) => {
    zeilen[22 + i] = `............${z}............`;
  });
  return zeilen.join('\n');
}

