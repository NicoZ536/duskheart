/** Zusatzframes einer Station: je Frame das Bild und der Quellframe, dessen Sockel er übernimmt. */
interface Zusatz {
  readonly bild: PixelFrameInput;
  readonly quelle: number;
}

/** Kopie eines M3-Sprites als Station `obj_<id>` in der Gruppe `stationen`, optional mit Zusatzframes. */
function alsStation(s: Sprite, zusatz: readonly Zusatz[] = [], zusatzClips: Readonly<Record<string, { frames: number[]; fps: number; loop: boolean }>> = {}): Sprite {
  const meta = spriteMeta(s, `${OBJ_PRAEFIX}${s.id}`);
  const frames: PixelFrameInput[] = [...s.frames.map((f) => ({ index: f.index, emissive: f.emissive, material: f.material, heightOverride: f.heightOverride })), ...zusatz.map((z) => z.bild)];
  const sockets = Object.fromEntries(Object.entries(s.sockets).map(([k, pts]) => [k, [...pts, ...zusatz.map((z) => pts[z.quelle] ?? pts[0] ?? [0, 0])].map((p) => [p[0], p[1]] as [number, number])]));
  // A station may stand mirrored (the build mode's F), like every station of `station()` (_stationen.ts).
  return spriteFromPixels({ ...meta, spiegelbar: true, group: STATIONEN_GRUPPE, clips: { ...meta.clips, ...zusatzClips }, sockets }, frames);
}

const brennt = lagerfeuer.clips.brennt?.frames ?? [];
const obj_lagerfeuer = alsStation(
  lagerfeuer,
  brennt.map((i) => {
    const f = lagerfeuer.frames[i];
    if (f === undefined) throw new Error(`lagerfeuer: Frame ${i} fehlt`);
    return { bild: ueberlagert(f, lagerfeuer.w, SPIESS, SPIESS_LEGENDE), quelle: i };
  }),
  { arbeitet: { frames: brennt.map((_, i) => lagerfeuer.frames.length + i), fps: 12, loop: true } },
);

