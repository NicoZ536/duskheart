/**
 * Die Koch-Stationen, das Vorratsfass und der Regensammler in der Welt (M7-25, M7-29, M7-30, docs/SPIEL.md §8 `obj_<id>`, §21;
 * strand E; Kontaktbogen `stationen.png`):
 * - **Kessel** (1×1): eiserner Topf auf drei Beinen; `arbeitet` lässt die Suppe blubbern und dampfen.
 * - **Backofen** (2×2): Lehmkuppel aus Ziegeln auf einem Feldsteinsockel, Rauchloch oben, das Maul vorn; `brennt` zeigt das
 *   Feuer im Maul (emissiv) und warmes Licht auf der Schwelle.
 * - **Räucherkammer** (1×1): schmale Bretterhütte mit Schindeldach, Fisch hinter der Klappe, Feuerkasten unten; `brennt`
 *   glüht unten und raucht am First.
 * - **Mühle** (1×1): zwei Mahlsteine auf einem Stumpf; `arbeitet` dreht den Griffzapfen.
 * - **Gärfass** (1×1): stehendes Fass mit Gärröhrchen; `arbeitet` steigen Blasen.
 * - **Kräutertisch** (2×1): Tisch mit Mörser und Stößel, Kräuterbündel, Wasserflasche; `arbeitet` stößt der Stößel.
 * - **Vorratsfass** (1×1): `zu` mit Deckel, `offen` mit Brot, Apfel und Wurst im Dunkel (Clips der Lager, `CHEST_CLIP`).
 * - **Regensammler** (1×1): Fass mit Brettertrichter, Wasser im Trichter (Materialflag `nass`).
 */
