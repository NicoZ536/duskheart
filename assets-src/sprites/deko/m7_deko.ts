/** Wandobjekte: flach an der Wand, Fuß an der Unterkante. */
const WAND: ReadonlySet<string> = new Set(['hirschgeweih_wand', 'kraeuterbund', 'blumenkranz', 'fischernetz_wand', 'muschelbild', 'muschelwindspiel', 'strandgutregal']);
/** Höhen-Hinweis der Bodenobjekte. */
const HOEHE: Readonly<Record<string, 'kugel' | 'zylinder' | 'block' | 'flach'>> = {'moosstein': 'kugel', 'farnkuebel': 'kugel', 'pilzstumpf': 'block', 'federgesteck': 'zylinder', 'wurzelskulptur': 'zylinder', 'rindenschale': 'kugel', 'muschelschale': 'kugel', 'treibholzskulptur': 'zylinder', 'steinanker': 'zylinder', 'buddelschiff': 'kugel', 'kieselmosaik': 'flach'};
/** Blätter, die im Wind wiegen. */
const WIND: Readonly<Record<string, string>> = {'farnkuebel': 'jih', 'kraeuterbund': 'jihg'};

function objekt(item: string): Sprite {
  const raster = DEKO_M7_RASTER[item];
  if (raster === undefined) throw new Error(`Deko M7: Raster ${item} fehlt`);
  const wand = WAND.has(item);
  const flach = HOEHE[item] === 'flach';
  const s = moebel({
    item,
    spiegelbar: false,
    size: [16, 16],
    anchor: wand || flach ? [8, 15] : [8, 14],
    hoehe: wand ? 'flach' : (HOEHE[item] ?? 'block'),
    frames: [raster],
    ...(WIND[item] === undefined ? {} : { wind: WIND[item] }),
    occluder: wand || flach ? { kind: 'none' } : { kind: 'ellipse', x: 8, y: 13, rx: 5, ry: 2 },
    ...(flach ? { schatten: 'none' as const } : {}),
  });
  return { ...s, group: DEKO_M7_GRUPPE };
}

export default Object.keys(DEKO_M7_RASTER).map(objekt);
