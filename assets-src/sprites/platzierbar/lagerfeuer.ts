/**
 * Lagerfeuer als platziertes Welt-Objekt (docs/SPIEL.md §6 `lagerfeuer`, MASTERPROMPT §12.2, §15.4,
 * M3-16, M3-22): Steinring aus neun Feldsteinen um eine Aschemulde, zwei gekreuzte Scheite. Zustände
 * nach Brennstoff als Clips (die Präsentation wählt sie aus dem Brennstoffstand der Simulation):
 * - `aus`: frisch geschichtet, nicht entzündet.
 * - `brennt`: volles Feuer, sechs Flammen-Frames mit 12 fps (Effekte schneller als Figuren, §4.5):
 *   Ruhe → Ducken (holt Luft, Antizipation) → Strecken mit abreißender Spitze (Überschwingen) →
 *   Neigen rechts → Flackern mit zwei Zungen → Neigen links; Funken steigen auf.
 * - `schwach`: Brennstoff fast aufgebraucht, kleine Flamme, vier Frames mit 10 fps.
 * - `glut`: kein Brennstoff mehr, die Mitte glimmt (zwei Helligkeiten, 4 fps).
 * - `asche`: erloschen, verkohlte Scheite und ein Aschehäufchen.
 * Flammen und Glut sind emissiv; der Kern ist heller als der Rand (feuer.5 unten innen, feuer.1 an den
 * Zungen). Sockel `licht` je Frame im Flammenkern (Höhe der Lichtquelle), `kochen` über dem Feuer
 * (Topf/Spieß, M5). 12 Farben inklusive Kontur (Asche in `stein.1`, damit `feuer.3` Platz hat).
 */
