/** Tor Nord-Süd, 16×48 über zwei Tiles: Pfostenkappen im Norden und Süden, Flügel von oben bzw. quer. */
function torSeite(zustand: 0 | 1 | 2): string {
  const zeilen: string[] = [];
  for (let y = 0; y < 48; y++) {
    let z = '................';
    const gy = y - 16;
    if (y <= 1) z = '....aeeda.......';
    else if (y <= 17) z = y === 17 ? '....kkkkk.......' : y === 2 ? '....aaaaa.......' : '....abcba.......';
    if (zustand === 0 && y >= 4 && y <= 31) z = `${z.slice(0, 7)}${y % 9 === 6 ? 'nN' : 'ed'}${z.slice(9)}`;
    if (zustand === 1 && y >= 4 && y <= 20) {
      const r = Math.min(6, Math.max(0, Math.floor((y - 4) / 2)));
      z = `${z.slice(0, 8)}${'dcbdcba'.slice(0, r + 1).padEnd(7, '.')}`.slice(0, 16);
    }
    if (zustand === 2 && y >= 4 && y <= 17) z = `${z.slice(0, 9)}${y === 4 ? 'aaaaaaa' : y === 17 ? 'kkkkkkk' : y % 5 === 1 ? '====nNa' : 'dcbdcba'}`;
    if (gy >= 14 && gy <= 15) z = '....aeeda.......';
    if (y >= 30 && y <= 31) z = '....aeeda.......';
    if (y >= 32 && y <= 45) z = y === 45 ? '....kkkkk.......' : y === 32 ? '....aaaaa.......' : '....abcba.......';
    zeilen.push(z.padEnd(16, '.').slice(0, 16));
  }
  return zeilen.join('\n');
}

