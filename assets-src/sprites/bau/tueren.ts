/**
 * Türen, Tor und Falltür T0–T1 (M4-12/M4-13, docs/SPIEL.md §8 „Türen `offen`/`zu`“): `bau_tuer_holz`,
 * `bau_tuer_verstaerkt`, `bau_tor_holz` (+ `bau_tor_holz_seite`), `bau_falltuer_holz` (+ Klappe) –
 * Frames und Clips nach dem Vertrag in `_bau.ts`.
 *
 * Eine Tür ist ein eigenes Wandelement mit Zarge (zwei Pfosten, Sturz), deshalb passt sie in jede
 * Wand: Die Sturzoberseite läuft in der Kappenzeile der Nachbarwände weiter. In einer Ost-West-Wand
 * zeigt das Blatt seine Bretter mit Querleisten, Beschlägen und Ring; es schwingt nach innen (Norden),
 * halb offen verkürzt es sich zur Trapezfläche, offen bleibt nur die Blattkante am Angelpfosten und
 * die Öffnung ist frei (dahinter erscheint der Boden des Raums). In einer Nord-Süd-Wand sieht man von
 * oben die Stirnseite des Nordpfostens und die Oberkante des Blatts; geöffnet steht das Blatt quer im
 * Raum und zeigt seine Fläche.
 * Frame 6 (`schnitt`) ist die auf 4 px gekappte Zarge für den Blick ins Haus (M4-27), passend zu den
 * Schnittfassungen der Wände.
 * - **Holz:** Brettertür mit Querleisten und eisernen Bändern.
 * - **Verstärkt:** dieselbe Tür mit Bronzebändern, Nietköpfen und Bronzering (Materialflag `metall`).
 * - **Tor:** zweiflügelig zwischen hohen Torpfosten mit Kappen, Flügel mit Andreaskreuz; für Wand- und
 *   Zaunlinien (ohne Sturz).
 * - **Falltür:** Luke mit Rahmen, Ring und Bändern im Boden; offen ein dunkler Schacht mit Leitersprossen,
 *   dazu die aufgestellte Klappe als aufrechtes Teil.
 */
