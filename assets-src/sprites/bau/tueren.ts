/** Frames 0–2 Ost-West (zu, halb, offen), 3–5 Nord-Süd, 6 Schnitt (Ost-West, Öffnung frei). */
function tuerRaster(): string[] {
  const offen = ueberlagere(ZARGE, BLATT_OFFEN);
  return [ueberlagere(ZARGE, BLATT_ZU), ueberlagere(ZARGE, BLATT_HALB), offen, ueberlagere(SEITE, SEITE_ZU), ueberlagere(SEITE, SEITE_HALB), ueberlagere(SEITE, SEITE_OFFEN), schnittRaster(offen)];
}

const TUER_CLIPS = {
  zu: [0],
  offen: [2],
  zu_seite: [3],
  offen_seite: [5],
  schnitt: [6],
};
const TUER_ANIMATION = {
  oeffnen: { frames: [0, 1, 2], fps: 12, loop: false },
  schliessen: { frames: [2, 1, 0], fps: 12, loop: false },
  oeffnen_seite: { frames: [3, 4, 5], fps: 12, loop: false },
  schliessen_seite: { frames: [5, 4, 3], fps: 12, loop: false },
};

function tuer(id: string, stil: Stil, raster: readonly string[]): ReturnType<typeof bauSprite> {
  return bauSprite(
    {
      id,
      size: AUFRECHT_ZELLE,
      anchor: AUFRECHT_ANKER,
      hoehe: 'flach',
      clips: { ...tabellenClips(TUER_CLIPS), ...TUER_ANIMATION },
      occluder: { kind: 'sprite' },
      schatten: 'silhouette',
    },
    raster.map((r) => rasterFrame(stil, r, AUFRECHT_ZELLE)),
  );
}

